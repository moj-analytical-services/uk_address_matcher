"""Benchmark to measure the recall of Splink's blocking rules.

This benchmark skips the exact matching phase and goes straight to the Splink
linker's blocking rules. It measures what fraction of true matches (by unique_id)
are found in the candidate set generated by the blocking rules.
"""

from pathlib import Path

import pandas as pd

from benchmarking.datasets import get_dataset_info, load_benchmark_data
from benchmarking.utils.io import setup_connection
from benchmarking.utils.timing import time_phase
from uk_address_matcher import get_linker

# ============================================================================
# Configuration
# ============================================================================

DATASET_NAME = "hackney_council"
OS_DATA_PATH: Path | None = None
SAMPLE_MODE = False

# Data cleaning configuration
CLEAN_CANONICAL_ON_THE_FLY = False
USE_EXPLODING_BLOCKING_RULE = True

# ============================================================================
# Setup
# ============================================================================

print("Initialising blocking recall benchmark environment...")
con = setup_connection()
df_messy_clean, df_os_clean = load_benchmark_data(
    con,
    DATASET_NAME,
    OS_DATA_PATH,
    include_term_frequencies=True,
    sample_mode=SAMPLE_MODE,
    clean_canonical_on_the_fly=CLEAN_CANONICAL_ON_THE_FLY,
    derive_term_frequencies_on_the_fly=False,
)

sql = """
select * exclude postcode, NULL as postcode
from df_messy_clean
"""
df_messy_clean = con.sql(sql)

# Get dataset info for reporting
dataset_info = get_dataset_info(DATASET_NAME)
dataset_info

variant_label = "blocking_recall"
variant_timings: dict[str, dict[str, float]] = {}

print(f"\n{'=' * 60}")
print(f"Blocking Recall Benchmark: {dataset_info.name}")
print(f"{'=' * 60}\n")

# ============================================================================
# Run blocking to get candidate pairs
# ============================================================================

# Remove dataset_name column for matching (will be joined back later if needed)
df_messy_for_matching = df_messy_clean.select("* EXCLUDE (dataset_name)")

with time_phase(variant_timings, variant_label, "get_linker"):
    linker = get_linker(
        df_addresses_to_match=df_messy_for_matching,
        df_addresses_to_search_within=df_os_clean,
        con=con,
        include_full_postcode_block=False,
        retain_intermediate_calculation_columns=False,
    )

linker_duration = variant_timings[variant_label]["get_linker"]
print(f"⏱  Linker setup completed in {linker_duration:.2f} seconds.\n")

if not USE_EXPLODING_BLOCKING_RULE:
    br_no_explode = [
        br
        for br in linker._settings_obj._blocking_rules_to_generate_predictions
        if "exploding" not in br.as_dict()["blocking_rule"]
    ]
    linker._settings_obj._blocking_rules_to_generate_predictions = br_no_explode

with time_phase(variant_timings, variant_label, "deterministic_link"):
    # deterministic_link applies blocking rules and returns candidate pairs
    df_blocked = linker.inference.deterministic_link()
    df_blocked_ddb = df_blocked.as_duckdbpyrelation()

blocking_duration = variant_timings[variant_label]["deterministic_link"]
print(f"⏱  Blocking (deterministic_link) completed in {blocking_duration:.2f} seconds.\n")

# ============================================================================
# Calculate blocking recall
# ============================================================================


print("--- Blocking Statistics ---\n")

# Total messy addresses
total_messy = df_messy_for_matching.count("*").fetchone()[0]

# True-match blocking recall: does the candidate set contain the ground-truth
# canonical UPRN for each messy record?
# unique_id_l = canonical UPRN, ukam_label_r = messy ground truth UPRN
true_matches_in_candidates = con.sql("""
    SELECT COUNT(DISTINCT ukam_address_id_r) AS count
    FROM df_blocked_ddb
    WHERE unique_id_l = ukam_label_r
""").fetchone()[0]

blocking_recall = true_matches_in_candidates / total_messy if total_messy > 0 else 0.0
print(
    "BLOCKING RECALL: "
    f"{blocking_recall:.1%} ({true_matches_in_candidates:,}/{total_messy:,} messy rows)\n"
)

# Count total candidate pairs
total_pairs = df_blocked_ddb.count("*").fetchone()[0]
print(f"Total candidate pairs generated: {total_pairs:,}")

# The blocked pairs have:
# - unique_id_l = canonical unique_id (UPRN from canonical data)
# - unique_id_r = messy unique_id (ground truth UPRN from messy data)
# - source_dataset_l = 'c_' (canonical), source_dataset_r = 'm_' (messy)

# Count unique messy addresses in candidates
unique_messy_in_candidates = con.sql("""
    SELECT COUNT(DISTINCT ukam_address_id_r) as count
    FROM df_blocked_ddb
""").fetchone()[0]
print(f"Unique messy addresses with candidates: {unique_messy_in_candidates:,}")

print(f"Total messy addresses: {total_messy:,}")

# Average candidates per messy address
avg_candidates = (
    total_pairs / unique_messy_in_candidates if unique_messy_in_candidates > 0 else 0
)
print(f"Average candidates per messy address: {avg_candidates:.1f}")

# Messy records with no candidates
messy_without_candidates = total_messy - unique_messy_in_candidates
print(f"Messy addresses with no candidates: {messy_without_candidates:,}")


# ============================================================================
# Examples: messy addresses with no candidates
# ============================================================================

print("\n--- Examples: messy addresses with no candidates ---\n")

pd.set_option("display.max_colwidth", 160)

misses_ddb = con.sql("""
WITH messy AS (
    SELECT
        unique_id,
        ukam_label,
        ukam_address_id,
        original_address_concat,
        clean_full_address
    FROM df_messy_clean
),
messy_with_candidates AS (
    SELECT DISTINCT ukam_address_id_r AS ukam_address_id
    FROM df_blocked_ddb
),
messy_without_candidates AS (
    SELECT m.*
    FROM messy m
    LEFT JOIN messy_with_candidates c USING (ukam_address_id)
    WHERE c.ukam_address_id IS NULL
),
truth AS (
    SELECT
        unique_id,
        original_address_concat AS true_original_address_concat,
        clean_full_address AS true_clean_full_address,
        ROW_NUMBER() OVER (PARTITION BY unique_id ORDER BY ukam_address_id) AS rn
    FROM df_os_clean
),
combined AS (
    SELECT
        m.unique_id,
        m.ukam_label AS uprn,
        m.original_address_concat AS messy_original_address,
        t.true_original_address_concat,
        m.clean_full_address AS messy_clean_full_address,
        t.true_clean_full_address
    FROM messy_without_candidates m
    LEFT JOIN truth t
        ON m.ukam_label = t.unique_id
        AND t.rn = 1
)
SELECT *
FROM combined
""")

misses_df = misses_ddb.df()
print(f"Messy rows with no candidates (computed here): {len(misses_df):,}")
print(f"Messy rows with no candidates (previous summary): {messy_without_candidates:,}\n")

n_show = 8
if len(misses_df) == 0:
    print("No misses found (all messy rows had at least one candidate).")
else:
    examples = misses_df.sample(n=min(n_show, len(misses_df)), random_state=42)
    examples = examples[
        [
            "unique_id",
            "uprn",
            "messy_original_address",
            "true_original_address_concat",
            "messy_clean_full_address",
            "true_clean_full_address",
        ]
    ].sort_values("uprn")
    print(examples.to_string(index=False))


# ============================================================================
# Summary
# ============================================================================


print(f"\n{'=' * 60}")
print("Blocking Recall Benchmark Complete")
print(f"{'=' * 60}")
